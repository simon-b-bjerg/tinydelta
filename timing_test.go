package tinydelta

import (
	"fmt"
	"math/rand"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestTimingInputs writes the inputs scripts/c-time.py times the C decoders
// on, as C files, into $TINYDELTA_TIMING_OUT (skipped without it): for each
// instruction set an old and a new firmware-like image (fakeFirmware, about
// 7 KB) and three patches between them: plain, coded (layout C), and coded
// with relocation (the map forced, so the engine runs whatever the encoder
// would pick).
func TestTimingInputs(t *testing.T) {
	out := os.Getenv("TINYDELTA_TIMING_OUT")
	if out == "" {
		t.Skip("TINYDELTA_TIMING_OUT not set")
	}
	array := func(b *strings.Builder, name string, data []byte) {
		fmt.Fprintf(b, "const unsigned char %s[%d] = {", name, len(data))
		for i, x := range data {
			if i%32 == 0 {
				b.WriteString("\n   ")
			}
			fmt.Fprintf(b, " %d,", x)
		}
		fmt.Fprintf(b, "\n};\nconst unsigned long %s_len = %d;\n", name, len(data))
	}
	for _, c := range relocCases {
		r := rand.New(rand.NewSource(73))
		old, new := fakeFirmware(r, c.arch, c.base, 45)
		plainPatch, err := Encode(old, new)
		if err != nil {
			t.Fatal(err)
		}
		m := relocMapFrom(old, new, rulesFor(c.arch), c.base).withDataRuns(old, new).withOutside(old, new)
		v1, _ := Encode(m.relocate(old), new)
		patches := map[string][]byte{
			"plain":     plainPatch,
			"coded":     encodeCoded(plainPatch, codedLayoutC),
			"relocated": encodeCodedReloc(v1, codedLayoutC, m),
		}
		for kind, p := range patches {
			if got, err := Decode(old, p); err != nil || string(got) != string(new) {
				t.Fatalf("%v %s: %v", c.arch, kind, err)
			}
			var b strings.Builder
			fmt.Fprintf(&b, "/* Generated by TestTimingInputs: %v, %s patch. */\n", c.arch, kind)
			array(&b, "old_image", old)
			array(&b, "patch", p)
			array(&b, "new_image", new)
			name := filepath.Join(out, fmt.Sprintf("%s_%s.c", strings.ToLower(c.arch.String()), kind))
			if err := os.WriteFile(name, []byte(b.String()), 0o644); err != nil {
				t.Fatal(err)
			}
			t.Logf("%s: old %d B, new %d B, patch %d B", name, len(old), len(new), len(p))
		}
	}
}
